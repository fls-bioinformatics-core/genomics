def verify_against_sample_sheet(fastq_dir, sample_sheet,
                                include_sample_dir=False):
    """
    Checks existence of predicted outputs from a sample sheet

    Arguments:
      fastq_dir (FastqDir): FastqDir instance to verify
      sample_sheet (str): path to sample sheet file
      include_sample_dir (bool): if True then include a
        'sample_name' directory level when checking for
        bcl2fastq2 outputs

    Returns:
      True if all the predicted outputs from the sample sheet are
        found, False otherwise.
    """
    return not bool(list_missing_fastqs(
        fastq_dir,
        sample_sheet,
        include_sample_dir=include_sample_dir))


def list_missing_fastqs(fastq_dir, sample_sheet,
                        include_sample_dir=False):
    """
    Lists missing Fastq files predicted from sample sheet

    Arguments:
      fastq_dir (FastqDir): FastqDir instance to check
      sample_sheet (str): path to a sample sheet file
      include_sample_dir (bool): if True then include
        a 'sample_name' directory level when checking
        for bcl2fastq2 outputs

    Returns:
      List: list of paths of missing Fastq files, relative
        to the unaligned directory. List is empty if there
        are no missing files.
    """
    # Initialise
    missing_fastqs = []
    # Gather information
    sample_sheet = SampleSheet(sample_sheet)
    if sample_sheet.has_lanes:
        lanes = None
    else:
        lanes = fastq_dir.lanes
    no_lane_splitting = ((len(fastq_dir.lanes) == 1) and
                         (fastq_dir.lanes[0] is None))
    # Set up predictor instance
    predictor = SampleSheetPredictor(sample_sheet=sample_sheet)
    predictor.set(package=fastq_dir.format,
                  paired_end=fastq_dir.paired_end,
                  lanes=lanes,
                  no_lane_splitting=no_lane_splitting,
                  force_sample_dir=include_sample_dir)
    # Loop over predictions and check corresponding outputs exist
    verified = True
    for proj in predictor.project_names:
        project = predictor.get_project(proj)
        for smpl in project.sample_ids:
            sample = project.get_sample(smpl)
            path = os.path.join(fastq_dir.path,
                                project.dir_name)
            if sample.dir_name:
                path = os.path.join(path,sample.dir_name)
            for fq in sample.fastqs():
                fastq = os.path.join(path, fq)
                if not os.path.exists(fastq):
                    missing_fastqs.append(
                        os.path.relpath(fastq, fastq_dir.path))
    # Return list of missing files
    return missing_fastqs


def summarise_projects(fastq_dir):
    """
    Short summary of projects, suitable for logging file

    The summary description is a one line summary of the project names
    along with the number of samples in each, and an indication if the
    run was paired-ended.

    Arguments:
      fastq_dir (FastqDir): FastqDir instance to summarise

    Returns:
      String: summary descriptions.
    """
    summary = ""
    project_summaries = []
    if fastq_dir.paired_end:
        summary = "Paired end: "
    for project in fastq_dir.projects:
        n_samples = len(project.samples)
        project_summaries.append(f"{project.name} "
                                 f"({n_samples} "
                                 f"sample{'s' if n_samples != 1 else ''})")
    summary += "; ".join(project_summaries)
    return summary


def describe_project(project):
    """
    Generate description string for samples in a project

    Description string gives the project name and a human-readable
    summary of the sample names, plus number of samples and whether
    the data is paired end.

    Example output: "Project Control: PhiX_1-2  (2 samples)"

    Arguments
      project (Project): Project instance

    Returns
      String: description of the project.
    """
    # Gather information
    paired_end = project.paired_end
    n_samples = len(project.samples)
    multiple_fastqs_per_sample = False
    for s in project.samples:
        n_fastqs = len(s.fastq)
        if (paired_end and n_fastqs > 2) or \
           (not paired_end and n_fastqs > 1):
            multiple_fastqs_per_sample = True
            break
    # Build description
    description = f"{project.name}: {project.pretty_print_samples()}"
    sample_names = project.pretty_print_samples()
    description += f" ({n_samples} "
    if paired_end:
        description += "paired end "
    if n_samples == 1:
        description += "sample"
    else:
        description += "samples"
    if multiple_fastqs_per_sample:
        description += ", multiple fastqs per sample"
    description += ")"
    return str(description)
