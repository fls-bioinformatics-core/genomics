"""
Provides classes for extracting data about Illumina sequencing runs
and derived data, by examining directory structures, data files and
naming conventions.

The main classes are:

* RunDir: for interacting with the sequencing data output from an
  Illumina sequencing instrument (e.g. NovaSeq 6000)
* FastqDir: for interacting the Fastq data output from Illumina
  BCL-to-Fastq conversion software (e.g. bcl2fastq)

Additional supporting classes for the 'RunDir' class are:

* RunInfo: extract data from the RunInfo.xml file in a run
* RunParameters: extract data from the RunParameters.xml file

Additional supporting classes for the 'FastqDir' class are:

* FastqDirProject: data about a "project" within the Fastq data
* FastqDirSample: data about a "sample" within the Fastq data

Typically only the 'RunDir' and 'FastqDir' classes are explicitly
instantiated; instances of the supporting are created implicitly
within the "top-level" classes. used within them to manage

The 'RunDir' class can be used to fetch information about
a run such as lanes, numbers of cycles and basecall file
format.

The 'FastqDir' class can be used to examine projects, samples
and Fastq files generated by the BCL-to-Fastq conversion.

In addition there are a number of utility functions:

* verify_against_sample_sheet: checks BCL-to-Fastq outputs
  against sample sheet file
* list_missing_fastqs: list missing predicted Fastqs
* summarise_projects: summarise projects in BCL-to-Fastq output
* describe_project: summaries samples in BCL-to-Fastq output
"""

